--
--   password_reset_tokens  — used if you use Laravel's built-in password reset
--   cache, cache_locks     — only if CACHE_STORE=database in .env
--   jobs, job_batches,
--   failed_jobs            — only if QUEUE_CONNECTION=database in .env
